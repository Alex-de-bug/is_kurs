/**
 * Модель WebSocket сообщения для real-time обновлений.
 *
 * Представляет сообщение, получаемое через WebSocket соединение от сервера.
 * Используется для уведомления клиента об изменениях в данных.
 *
 * Компоненты подписываются на эти сообщения и обновляют свои данные
 * только если изменения касаются отображаемых объектов.
 *
 * @property model - Тип модели, которая была изменена (task, user, sprint, team и т.д.)
 * @property id - Идентификатор конкретного объекта (может быть null для глобальных обновлений)
 */
export interface WebsocketMessage {
  model: string,
  id: string | null
}
