/**
 * Обобщенная модель страницы с пагинацией.
 *
 * Представляет один "срез" данных из полного набора с информацией о пагинации.
 * Используется для всех списков с пагинацией в приложении (задачи, спринты, пользователи и т.д.)
 *
 * @typeParam T - Тип элементов в массиве content
 *
 * @property content - Массив элементов на текущей странице
 * @property page - Метаданные пагинации
 */
export interface Page<T> {
  content: T[],
  page: PageInfo
}

/**
 * Информация о пагинации.
 *
 * Содержит метаданные о текущей странице и общем количестве данных.
 * Используется для построения UI элементов пагинации (кнопки переключения страниц).
 *
 * @property size - Размер страницы (количество элементов на странице)
 * @property number - Номер текущей страницы (начиная с 0)
 * @property totalElements - Общее количество элементов во всем наборе данных
 * @property totalPages - Общее количество страниц
 */
export interface PageInfo {
  size: number,
  number: number,
  totalElements: number,
  totalPages: number
}
